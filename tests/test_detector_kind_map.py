"""ADR-067 P1 addendum: the detector -> ChangeKind map behind per-rule
``not_evaluated``, checked for drift, completeness and runtime soundness.

The committed module ``abicheck/policy/detector_kind_map.py`` is generated by
``scripts/gen_detector_kind_map.py``. These tests fail when it is stale, when
a registered detector or a ``ChangeKind`` is missing from it, or when a
detector emits a kind the map does not credit it with on the controlled
mutation catalogue (an under-approximation would make a rule read
``not_evaluated`` when a detector that could have checked it did run).
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest
from _detector_mutations import MUTATIONS, build_snapshot

from abicheck.detector_registry import registry
from abicheck.model.change_catalog.kinds import ChangeKind
from abicheck.policy.detector_kind_map import DETECTOR_KINDS, NON_DETECTOR_KINDS

ROOT = Path(__file__).resolve().parents[1]


def _generator():
    path = ROOT / "scripts" / "gen_detector_kind_map.py"
    spec = importlib.util.spec_from_file_location("gen_detector_kind_map", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def registered() -> None:
    registry.ensure_loaded()


def test_committed_map_matches_a_fresh_derivation(registered: None) -> None:
    """Drift gate: the committed data is what the generator derives today."""
    derived = _generator().derive()
    assert derived == (dict(DETECTOR_KINDS), NON_DETECTOR_KINDS)


def test_every_registered_detector_has_an_entry(registered: None) -> None:
    assert set(DETECTOR_KINDS) == set(registry.detector_names)


def test_every_change_kind_is_produced_by_a_detector_or_listed_outside_the_registry(
    registered: None,
) -> None:
    produced: set[str] = set().union(*DETECTOR_KINDS.values())
    every = {member.value for member in ChangeKind}
    # Completeness: nothing is unaccounted for ...
    assert produced | NON_DETECTOR_KINDS == every
    # ... and nothing is claimed twice.
    assert not produced & NON_DETECTOR_KINDS


def test_every_registered_detector_can_emit_at_least_one_kind(
    registered: None,
) -> None:
    silent = sorted(name for name, kinds in DETECTOR_KINDS.items() if not kinds)
    assert silent == []


@pytest.mark.parametrize(
    ("kind", "producers"),
    [
        # A DWARF-only kind: a rule scoped to it must not be credited to any
        # detector that runs on an ELF-only comparison.
        ("struct_size_changed", {"dwarf"}),
        ("struct_field_offset_changed", {"dwarf"}),
        # An ELF symbol kind, produced by the ELF detector alone.
        ("symbol_size_changed", {"elf"}),
        # A kind a source-diff pipeline step emits (buildsource/source_diff.py),
        # reached from no registered detector.
        ("inline_body_changed", set()),
    ],
)
def test_pinned_kinds_have_the_producers_read_from_the_source(
    registered: None, kind: str, producers: set[str]
) -> None:
    found = {name for name, kinds in DETECTOR_KINDS.items() if kind in kinds}
    assert found == producers
    assert (kind in NON_DETECTOR_KINDS) is (not producers)


def test_mutation_catalogue_emissions_are_credited_to_their_detector(
    registered: None,
) -> None:
    """Soundness on real detector output: every kind a detector emits on the
    controlled mutation catalogue (both directions, two tags) is in its entry.
    The detector runs only when its own evidence gate admits it, as in a real
    comparison, so a refused detector contributes nothing here."""
    missing: list[tuple[str, str, str]] = []
    for mutation in MUTATIONS:
        for tag in (1, 2):
            old_extra, new_extra, expected, _breaking = mutation(tag)
            for before, after in ((old_extra, new_extra), (new_extra, old_extra)):
                old = build_snapshot("1.0", {}, before)
                new = build_snapshot("2.0", {}, after)
                for entry in registry._detectors:  # noqa: SLF001
                    if (
                        entry.support_fn is not None
                        and not entry.support_fn(old, new)[0]
                    ):
                        continue
                    for change in entry.fn(old, new):
                        if change.kind.value not in DETECTOR_KINDS[entry.name]:
                            missing.append(
                                (mutation.__name__, entry.name, change.kind.value)
                            )
                # The catalogue's own oracle kind has at least one producer.
                assert expected.value in {
                    k for ks in DETECTOR_KINDS.values() for k in ks
                }
    assert missing == []
