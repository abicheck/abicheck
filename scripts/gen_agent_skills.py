"""gen_agent_skills.py — publish `skills-src/` as self-contained Agent Skills.

ADR-058 / plan G36 P0.3. `skills-src/` is the one hand-authored copy: each
skill's `SKILL.md` plus its own `references/`, and one `shared/` tree of
Layer-B domain fragments every skill cites by link. This generator resolves
what each skill actually cites (transitively — a fragment may cite another
fragment), **copies** it into that skill's own `references/shared/`, and
rewrites every link so the installed skill resolves entirely inside its own
directory.

Copies, never symlinks: an installed skill is read from the perspective of one
directory, and a marketplace zip, a `skills.sh` subset install, or a Windows
checkout each break a live cross-skill link differently (ADR-058, "Source-of-
truth and publication model").

Three output trees, same content:

* ``.agents/skills/``  — the canonical portable target (Copilot, Codex, Cursor
  read it directly).
* ``.claude/skills/``  — Claude Code does not scan ``.agents/skills``.
* ``.gemini/skills/``  — nor does Gemini CLI.

Links pointing at this repository's own ``docs/`` pages are rewritten to the
published documentation site, whose host comes from ``mkdocs.yml``'s
``site_url`` and whose URL shape comes from ``mkdocs.yml``'s
``use_directory_urls`` (mkdocs's own default, ``true``, when the key is
absent) — never a hardcoded literal, so the generator cannot silently emit
broken links if either is ever changed.

Usage:
    python scripts/gen_agent_skills.py            # write the trees
    python scripts/gen_agent_skills.py --check    # verify in sync (CI)
"""

