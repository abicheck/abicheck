def _strip_front_matter(text: str) -> str:
    return _FRONT_MATTER_RE.sub("", text, count=1)


def _split_front_matter(text: str) -> tuple[str, str]:
    match = _FRONT_MATTER_RE.match(text)
    if match is None:
        return "", text
    return match.group(0), text[match.end() :]


def _rewrite_target(
    source_path: Path,
    out_rel: str,
    target: str,
    shared_names: set[str],
    shared_dir: Path,
    docs_dir: Path,
    containment_root: Path,
) -> str:
    """Rewrite one link target for its position in the generated tree.

    `out_rel` is the generated file's path relative to the skill root, which
    is what a `shared/` fragment link must be made relative to.
    `containment_root` is the source directory this file's own relative links
    may not escape — the skill's own directory for a `SKILL.md`/`references/`
    file, and `shared/` for a fragment (whose only legitimate relative links
    are sibling fragments, already handled above).
    """
    if target.startswith("/"):
        # Root-relative: resolved against whatever host or filesystem root
        # renders the installed skill, which is neither the skill's own
        # directory nor abicheck's docs site. There is no correct rewrite —
        # the intended base is unknowable — so reject rather than publish a
        # link whose meaning depends on where it is read.
        raise SkillGenerationError(
            f"{source_path.relative_to(REPO_DIR).as_posix()}: root-relative "
            f"link {target!r} — write a path relative to this file, or a full "
            "URL. A leading slash resolves against the reader's root, not the "
            "installed skill."
        )

    if "://" in target or target.startswith(("#", "mailto:")):
        return target

    bare, _, anchor = target.partition("#")
    anchor = f"#{anchor}" if anchor else ""
    if not bare:
        return target

    fragment = _shared_fragment_for(source_path, target, shared_dir)
    if fragment is not None:
        if fragment not in shared_names:  # pragma: no cover - resolver is exhaustive
            raise SkillGenerationError(
                f"{source_path.relative_to(REPO_DIR).as_posix()}: cites "
                f"fragment {fragment!r} that was not resolved for this skill"
            )
        destination = Path(SHARED_SUBDIR) / fragment
        return _relative_link(Path(out_rel), destination) + anchor

    resolved = (source_path.parent / bare).resolve()
    try:
        docs_relative = resolved.relative_to(docs_dir.resolve()).as_posix()
    except ValueError:
        docs_relative = None
    if docs_relative is not None:
        if not resolved.is_file():
            raise SkillGenerationError(
                f"{source_path.relative_to(REPO_DIR).as_posix()}: links to "
                f"docs page {bare!r}, which does not exist"
            )
        return published_docs_url(docs_relative, anchor)

    # A link that stays inside the skill's own tree (SKILL.md ->
    # references/foo.md) needs no rewriting; anything else escapes the
    # installed directory and is a hard error rather than a silent copy.
    try:
        resolved.relative_to(containment_root.resolve())
    except ValueError:
        raise SkillGenerationError(
            f"{source_path.relative_to(REPO_DIR).as_posix()}: link {target!r} "
            "escapes the skill's own directory and is neither a shared "
            "fragment nor a docs/ page"
        ) from None

    # Contained is necessary but not sufficient: `render_skill` publishes
    # `SKILL.md` and `references/**/*.md` and nothing else, so a link to a
    # contained path the generator does not copy (`references/data.json`, a
    # `notes.md` beside `SKILL.md`) is preserved verbatim and then dangles in
    # every installed tree. The link must name a file that actually ships.
    rel = resolved.relative_to(containment_root.resolve())
    ships = (
        resolved.is_file()
        and resolved.suffix == ".md"
        and (
            # A `shared/` fragment's siblings are published flat beside it.
            containment_root.resolve() == shared_dir.resolve()
            or rel.as_posix() == "SKILL.md"
            or rel.parts[:1] == ("references",)
        )
    )
    if not ships:
        raise SkillGenerationError(
            f"{source_path.relative_to(REPO_DIR).as_posix()}: link {target!r} "
            "points inside the skill but at something this generator does not "
            "publish. Only `SKILL.md` and `references/**/*.md` are copied, so "
            "any other target would dangle in the installed skill."
        )
    return target


def _relative_link(from_rel: Path, to_rel: Path) -> str:
    """POSIX relative link from one skill-relative file to another."""
    from_parts = from_rel.parent.parts
    to_parts = to_rel.parts
    common = 0
    while (
        common < len(from_parts)
        and common < len(to_parts) - 1
        and from_parts[common] == to_parts[common]
    ):
        common += 1
    ups = [".."] * (len(from_parts) - common)
    return "/".join([*ups, *to_parts[common:]])


def _render(
    source_path: Path,
    out_rel: str,
    shared_names: set[str],
    *,
    keep_front_matter: bool,
    containment_root: Path,
    shared_dir: Path | None = None,
    docs_dir: Path | None = None,
) -> str:
    shared_dir = SHARED_DIR if shared_dir is None else shared_dir
    docs_dir = DOCS_DIR if docs_dir is None else docs_dir
    text = source_path.read_text(encoding="utf-8")
    front_matter, body = _split_front_matter(text)

    # One guard for every container — block quote, list indent, tab, and any
    # nesting of them. Enumerating containers separately left their
    # combinations uncovered; see `_CONTAINED_FENCE_RE`.
    contained = _contained_fence_line(body)
    if contained is not None:
        line, prefix = contained
        raise SkillGenerationError(
            f"{source_path}: line ~{line}: fenced code block behind the "
            f"container prefix {prefix!r}. The mask anchors on the line start "
            "and reads at most three leading spaces, so the block would be "
            "processed as prose and its example links rewritten. Move the "
            "example out of its container, to the left margin."
        )

    # Checked at the `_mask_block_code` midpoint, exactly like the container
    # guard. An earlier version scanned the raw body on the theory that
    # masking is what an escape corrupts — but that is only true of *inline*
    # pairing. The block-level passes match fence delimiters at line starts
    # and never pair backticks, so an escape cannot mislead them, and running
    # first means a `\[` inside a legitimate regex or C-string example is
    # already hidden. Scanning raw rejected those valid examples outright.
    escaped_body = _mask_block_code(body, {})
    escape = _STRUCTURAL_ESCAPE_RE.search(escaped_body)
    if escape is not None:
        line = escaped_body.count("\n", 0, escape.start()) + 1
        raise SkillGenerationError(
            f"{source_path}: line ~{line}: backslash-escaped {escape.group()!r}. "
            "CommonMark makes it a literal, but the code-span and link "
            "patterns here still read it structurally — an escaped backtick "
            "pair masks a real link (which then ships repo-relative), and an "
            "escaped bracket makes prose look like a link. Use a code span, "
            "or reword to avoid the escape."
        )

    # Code examples are literal content: their link syntax must be neither
    # rewritten nor validated. Everything below operates on masked text.
    body, code_regions = mask_code_regions(body)

    ref_defs = _reference_definition_labels(body)
    if ref_defs:
        raise SkillGenerationError(
            f"{source_path}: reference-style link definition(s) "
            f"{sorted(ref_defs)} — skill sources must use inline "
            "`[text](target)` links only. The link rewrite does not see a "
            "reference definition, so it would be published verbatim and "
            "point outside the installed skill."
        )

    images = [m.group(2) for m in _MD_IMAGE_RE.finditer(body)]
    if images:
        raise SkillGenerationError(
            f"{source_path}: Markdown image(s) {sorted(images)} — this "
            "generator publishes Markdown only and never rewrites an image "
            "destination, so the installed skill would reference an asset it "
            "does not contain. Describe the diagram in text, or link the "
            "published docs page that hosts it."
        )

    _reject_unrewritable_links(source_path, body)

    def replace(match: re.Match[str]) -> str:
        label, target, title = match.group(1), match.group(2), match.group(3) or ""
        new_target = _rewrite_target(
            source_path,
            out_rel,
            target,
            shared_names,
            shared_dir,
            docs_dir,
            containment_root,
        )
        return f"[{label}]({new_target}{title})"

    body = unmask_code_regions(_MD_LINK_RE.sub(replace, body), code_regions)
    head = front_matter if keep_front_matter else ""
    return f"{head}{GENERATED_MARKER}\n\n{body.lstrip(chr(10))}"


def render_skill(skill_dir: Path, shared_dir: Path | None = None) -> dict[str, str]:
    """The complete generated content of one skill, keyed by skill-relative path.

    `shared_dir` defaults to the module-global `SHARED_DIR`, but a caller
    rendering a different source tree must pass that tree's own `shared/` —
    resolving fragments against one tree while discovering skills in another
    would mix two unrelated sources into one output.
    """
    shared_dir = SHARED_DIR if shared_dir is None else shared_dir
    fragments = resolve_shared_fragments(skill_dir, shared_dir)
    shared_names = set(fragments)
    out: dict[str, str] = {}

    out["SKILL.md"] = _render(
        skill_dir / "SKILL.md",
        "SKILL.md",
        shared_names,
        keep_front_matter=True,
        containment_root=skill_dir,
        shared_dir=shared_dir,
    )

    references = skill_dir / "references"
    if references.is_dir():
        for path in sorted(references.rglob("*.md")):
            rel = f"references/{path.relative_to(references).as_posix()}"
            out[rel] = _render(
                path,
                rel,
                shared_names,
                keep_front_matter=False,
                containment_root=skill_dir,
                shared_dir=shared_dir,
            )

    for name in fragments:
        rel = f"{SHARED_SUBDIR}/{name}"
        if rel in out:
            # A skill-specific `references/shared/<name>.md` was rendered
            # above and the skill also cites the global fragment of that
            # name. Assigning here would silently replace the skill's own
            # file with the global one — generation and `--check` would both
            # pass while every published tree served content the skill's own
            # links did not mean.
            raise SkillGenerationError(
                f"{skill_dir.name}: {rel!r} is produced twice — once from "
                f"this skill's own `references/shared/{name}` and once from "
                f"the global `shared/{name}` it cites. Rename the "
                "skill-specific file; `references/shared/` is reserved for "
                "copied global fragments."
            )
        out[rel] = _render(
            shared_dir / name,
            rel,
            shared_names,
            keep_front_matter=False,
            containment_root=shared_dir,
            shared_dir=shared_dir,
        )
    return out


def render_all(src_dir: Path | None = None) -> dict[str, str]:
    """Every generated file, keyed by `<skill-name>/<skill-relative path>`.

    Also enforces the no-orphan rule: a `shared/` fragment no skill cites,
    directly or transitively, is dead content and fails generation.
    """
    src_dir = SRC_DIR if src_dir is None else src_dir
    # The shared tree always belongs to the source tree being rendered, never
    # to whatever the module globals happen to point at — otherwise a caller
    # rendering an alternate `src_dir` silently resolves fragments against,
    # and orphan-checks, this repository's own `skills-src/shared/`.
    shared_dir = src_dir / "shared"
    skills = discover_skills(src_dir)
    if not skills:
        raise SkillGenerationError(f"no skills found under {src_dir}")

    rendered: dict[str, str] = {}
    cited: set[str] = set()
    for skill_dir in skills:
        cited.update(resolve_shared_fragments(skill_dir, shared_dir))
        for rel, content in render_skill(skill_dir, shared_dir).items():
            rendered[f"{skill_dir.name}/{rel}"] = content

    available = (
        {p.name for p in shared_dir.glob("*.md")} if shared_dir.is_dir() else set()
    )
    orphans = sorted(available - cited)
    if orphans:
        raise SkillGenerationError(
            "shared fragment(s) never cited by any skill (directly or "
            f"transitively): {', '.join(orphans)} — cite them or delete them"
        )
    return rendered


