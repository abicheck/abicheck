"""gen_cjm_stage_table.py — the CJM stage coverage table, counted from the
use-case registry instead of hand-typed.

Splices the table between `<!-- BEGIN GENERATED: cjm-stage-table -->` /
`<!-- END GENERATED: cjm-stage-table -->` sentinels in
`docs/contribute/cjm.md` (the same splice pattern `gen_platform_matrix.py`
uses). One row per stage, in the order its `### \\`stage\\`` heading appears
in cjm.md; each cell counts the registry use cases whose `journey_stages`
list the stage, grouped by their `status`.

Usage:
    python scripts/gen_cjm_stage_table.py            # write the table
    python scripts/gen_cjm_stage_table.py --check    # verify in sync (CI)
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

import yaml

REPO_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_DIR / "scripts"))

from generated_section import splice_generated  # noqa: E402

CJM_PATH = REPO_DIR / "docs" / "contribute" / "cjm.md"
REGISTRY_PATH = REPO_DIR / "docs" / "contribute" / "usecase-registry.yaml"
_MARKER = "cjm-stage-table"

STATUSES = ("complete", "partial", "modeled", "planned", "by_design_excluded")

GENERATED_NOTE = (
    "<!-- The table in this section is GENERATED by "
    "scripts/gen_cjm_stage_table.py from docs/contribute/usecase-registry.yaml "
    "— do not edit by hand. Run `python scripts/gen_cjm_stage_table.py` to "
    "regenerate. -->"
)

_STAGE_HEADING = re.compile(r"^### `([a-z_]+)`\s*$", re.MULTILINE)


def stage_keys(cjm_text: str) -> list[str]:
    """Stage keys in the order their `### \\`stage\\`` headings appear."""
    return _STAGE_HEADING.findall(cjm_text)


def count_by_stage(registry: dict) -> dict[str, Counter]:
    counts: dict[str, Counter] = {}
    for case in registry["use_cases"]:
        for stage in case.get("journey_stages", []):
            counts.setdefault(stage, Counter())[case["status"]] += 1
    return counts


def render(stages: list[str], counts: dict[str, Counter]) -> str:
    lines = [
        GENERATED_NOTE,
        "",
        "| Stage | " + " | ".join(STATUSES) + " |",
        "|---|" + "---:|" * len(STATUSES),
    ]
    for stage in stages:
        c = counts.get(stage, Counter())
        cells = " | ".join(str(c[status]) for status in STATUSES)
        lines.append(f"| `{stage}` | {cells} |")
    return "\n".join(lines) + "\n"


def _load_registry(path: Path) -> dict:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or "use_cases" not in data:
        raise ValueError(f"{path}: no use_cases list")
    return data


def build(cjm_path: Path, registry_path: Path) -> tuple[str, str]:
    """(current text of the CJM page, the page with its table regenerated)."""
    current = cjm_path.read_text(encoding="utf-8")
    stages = stage_keys(current)
    counts = count_by_stage(_load_registry(registry_path))
    rendered = splice_generated(current, _MARKER, render(stages, counts), cjm_path)
    return current, rendered


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed file is in sync instead of writing it",
    )
    parser.add_argument("--cjm", type=Path, default=CJM_PATH, help=argparse.SUPPRESS)
    parser.add_argument(
        "--registry", type=Path, default=REGISTRY_PATH, help=argparse.SUPPRESS
    )
    args = parser.parse_args(argv)

    current, rendered = build(args.cjm, args.registry)
    rel = (
        args.cjm.relative_to(REPO_DIR)
        if args.cjm.is_relative_to(REPO_DIR)
        else args.cjm
    )

    if args.check:
        if rendered != current:
            print(
                f"{rel}'s generated cjm-stage-table section is stale — "
                "regenerate with:",
                file=sys.stderr,
            )
            print("  python scripts/gen_cjm_stage_table.py", file=sys.stderr)
            return 1
        print(f"{rel}'s cjm-stage-table section is in sync")
        return 0

    args.cjm.write_text(rendered, encoding="utf-8")
    print(f"wrote {rel}'s cjm-stage-table section")
    return 0


if __name__ == "__main__":
    sys.exit(main())
