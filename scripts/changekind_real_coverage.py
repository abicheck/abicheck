#!/usr/bin/env python3
"""Real-extraction coverage inventory for every ``ChangeKind``.

A detector covered only by unit tests on hand-built snapshots can look
"tested" while the real extractor never produces the fact it reads
(``ctor_explicit_added`` was exactly that). This script records, for every
``ChangeKind``, which *real end-to-end* evidence sources name it:

``catalog``
    ``catalog/ground_truth.json`` ``verdicts[case].expected_kinds`` -- the
    cases ``tests/validate_examples.py`` builds and runs through the real CLI.
``field_shapes``
    ``tests/field_shapes/*/ground_truth.json`` ``expected_kinds`` -- run by
    ``tests/test_field_shapes.py``.
``integration``
    ``tests/**/*.py`` test functions carrying the ``integration`` marker
    (module ``pytestmark``, class decorator, or function decorator) that
    reference the kind -- see :func:`scan_integration_tests` for the exact
    heuristic and its limits.

Kinds are grouped by their designed evidence tier
(``scripts/evidence_tiers.py`` ``EVIDENCE_TIER_BY_KIND``; ``unmapped`` when a
kind has no entry). Naming a kind is a *claim* of end-to-end evidence, not
proof that the run passes on every platform: a catalog case may be skipped on
a host, and the integration scan is lexical.

Requires the package installed (``pip install -e .``): it imports
``abicheck.checker_policy`` for the kind list and verdict sets. Otherwise
stdlib only.

Usage::

    python scripts/changekind_real_coverage.py            # rewrite the doc
    python scripts/changekind_real_coverage.py --check    # fail on doc drift
    python scripts/changekind_real_coverage.py --json out.json
    python scripts/changekind_real_coverage.py --write-baseline

The shrink-only zero-source baseline is
``scripts/changekind_real_coverage_baseline.json``, gated by
``tests/test_changekind_real_coverage.py``.
"""

from __future__ import annotations

import argparse
import ast
import json
import sys
from collections.abc import Iterable, Iterator
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = ROOT / "scripts"
TESTS = ROOT / "tests"
CATALOG_GT = ROOT / "catalog" / "ground_truth.json"
FIELD_SHAPES = TESTS / "field_shapes"
DOC_PATH = ROOT / "docs" / "contribute" / "changekind-real-coverage.md"
BASELINE_PATH = SCRIPTS / "changekind_real_coverage_baseline.json"
SOURCES = ("catalog", "field_shapes", "integration")
TOP_N = 20

# This checkout's package, not whichever abicheck is installed elsewhere.
for _p in (str(SCRIPTS), str(ROOT)):
    if _p not in sys.path:
        sys.path.insert(0, _p)

import evidence_tiers  # noqa: E402

GENERATED_BANNER = (
    "<!-- GENERATED by scripts/changekind_real_coverage.py -- do not edit by "
    "hand. Run `python scripts/changekind_real_coverage.py` to regenerate. -->"
)


def all_kinds() -> dict[str, str]:
    """Map every ``ChangeKind`` value to its member name."""
    from abicheck.checker_policy import ChangeKind

    return {k.value: k.name for k in ChangeKind}


def verdict_class(value: str) -> str:
    from abicheck.checker_policy import (
        API_BREAK_KINDS,
        BREAKING_KINDS,
        RISK_KINDS,
        ChangeKind,
    )

    kind = ChangeKind(value)
    if kind in BREAKING_KINDS:
        return "BREAKING"
    if kind in API_BREAK_KINDS:
        return "API_BREAK"
    if kind in RISK_KINDS:
        return "RISK"
    return "COMPATIBLE"


def scan_catalog(path: Path = CATALOG_GT) -> dict[str, set[str]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    out: dict[str, set[str]] = {}
    for case, info in data.get("verdicts", {}).items():
        for kind in info.get("expected_kinds") or []:
            out.setdefault(kind, set()).add(case)
    return out


def scan_field_shapes(root: Path = FIELD_SHAPES) -> dict[str, set[str]]:
    out: dict[str, set[str]] = {}
    for gt in sorted(root.glob("*/ground_truth.json")):
        data = json.loads(gt.read_text(encoding="utf-8"))
        for kind in data.get("expected_kinds") or []:
            out.setdefault(kind, set()).add(gt.parent.name)
    return out


def _is_integration_mark(node: ast.AST) -> bool:
    """True for ``pytest.mark.integration`` / ``mark.integration`` (called or not)."""
    if isinstance(node, ast.Call):
        node = node.func
    return (
        isinstance(node, ast.Attribute)
        and node.attr == "integration"
        and isinstance(node.value, ast.Attribute)
        and node.value.attr == "mark"
    )


def _marks_in(expr: ast.AST | None) -> bool:
    if expr is None:
        return False
    if isinstance(expr, (ast.List, ast.Tuple)):
        return any(_is_integration_mark(e) for e in expr.elts)
    return _is_integration_mark(expr)


def _module_is_integration(tree: ast.Module) -> bool:
    for stmt in tree.body:
        targets: list[ast.expr] = []
        value: ast.AST | None = None
        if isinstance(stmt, ast.Assign):
            targets, value = list(stmt.targets), stmt.value
        elif isinstance(stmt, ast.AnnAssign):
            targets, value = [stmt.target], stmt.value
        if any(isinstance(t, ast.Name) and t.id == "pytestmark" for t in targets):
            if _marks_in(value):
                return True
    return False


def _kind_refs(
    nodes: Iterable[ast.AST], values: set[str], names: dict[str, str]
) -> set[str]:
    """Kind values referenced as ``ChangeKind.NAME`` or as an exact string literal."""
    found: set[str] = set()
    for root in nodes:
        for node in ast.walk(root):
            if (
                isinstance(node, ast.Attribute)
                and node.attr in names
                and isinstance(node.value, ast.Name)
                and node.value.id == "ChangeKind"
            ):
                found.add(names[node.attr])
            elif (
                isinstance(node, ast.Constant)
                and isinstance(node.value, str)
                and node.value in values
            ):
                found.add(node.value)
    return found


def _test_functions(
    tree: ast.Module, module_marked: bool
) -> Iterator[tuple[str, ast.FunctionDef | ast.AsyncFunctionDef, bool]]:
    def visit(
        body: list[ast.stmt], prefix: str, marked: bool
    ) -> Iterator[tuple[str, ast.FunctionDef | ast.AsyncFunctionDef, bool]]:
        for stmt in body:
            if isinstance(stmt, ast.ClassDef):
                cls_marked = marked or any(
                    _is_integration_mark(d) for d in stmt.decorator_list
                )
                yield from visit(stmt.body, f"{prefix}{stmt.name}::", cls_marked)
            elif isinstance(
                stmt, (ast.FunctionDef, ast.AsyncFunctionDef)
            ) and stmt.name.startswith("test"):
                fn_marked = marked or any(
                    _is_integration_mark(d) for d in stmt.decorator_list
                )
                yield f"{prefix}{stmt.name}", stmt, fn_marked

    yield from visit(tree.body, "", module_marked)


def scan_integration_tests(
    root: Path = TESTS, kinds: dict[str, str] | None = None
) -> dict[str, set[str]]:
    """Kinds asserted by ``integration``-marked tests.

    Heuristic (lexical, per test function):

    * a test is integration when its module-level ``pytestmark`` (a single
      mark or a list/tuple), an enclosing class decorator, or its own
      decorator is ``pytest.mark.integration``. Marks applied via
      ``conftest.py`` hooks, ``pytest.param(marks=...)`` or ``-m`` aliases
      are **not** seen;
    * a kind counts when it appears inside an ``assert`` statement of that
      test or in one of its ``pytest.mark.parametrize`` decorators, as
      ``ChangeKind.NAME`` or as the exact string value. A kind asserted only
      inside a helper the test calls is **not** seen (false negative), and a
      string literal that equals a kind value but means something else (or an
      ``assert X not in kinds``) is counted (false positive).
    """
    kinds = kinds if kinds is not None else all_kinds()
    values = set(kinds)
    names = {name: value for value, name in kinds.items()}
    out: dict[str, set[str]] = {}
    for path in sorted(root.rglob("*.py")):
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except (SyntaxError, UnicodeDecodeError):
            continue
        module_marked = _module_is_integration(tree)
        rel = path.relative_to(ROOT).as_posix()
        for qual, fn, marked in _test_functions(tree, module_marked):
            if not marked:
                continue
            scope: list[ast.AST] = [
                n for n in ast.walk(fn) if isinstance(n, ast.Assert)
            ]
            scope += [
                d
                for d in fn.decorator_list
                if isinstance(d, ast.Call)
                and isinstance(d.func, ast.Attribute)
                and d.func.attr == "parametrize"
            ]
            for kind in _kind_refs(scope, values, names):
                out.setdefault(kind, set()).add(f"{rel}::{qual}")
    return out


def build_inventory() -> dict[str, dict[str, object]]:
    kinds = all_kinds()
    scans = {
        "catalog": scan_catalog(),
        "field_shapes": scan_field_shapes(),
        "integration": scan_integration_tests(kinds=kinds),
    }
    inv: dict[str, dict[str, object]] = {}
    for value in sorted(kinds):
        sources = {src: sorted(scans[src].get(value, ())) for src in SOURCES}
        inv[value] = {
            "name": kinds[value],
            "tier": evidence_tiers.EVIDENCE_TIER_BY_KIND.get(value, "unmapped"),
            "verdict": verdict_class(value),
            "sources": sources,
            "source_count": sum(len(v) for v in sources.values()),
        }
    return inv


def zero_source_kinds(inv: dict[str, dict[str, object]]) -> list[str]:
    return sorted(k for k, v in inv.items() if v["source_count"] == 0)


_VERDICT_RANK = {"BREAKING": 0, "API_BREAK": 1, "RISK": 2, "COMPATIBLE": 3}
_TIERS = [*evidence_tiers.TIER_ORDER, "unmapped"]


def most_important_gaps(inv: dict[str, dict[str, object]], n: int = TOP_N) -> list[str]:
    """Zero-source kinds ranked BREAKING, API_BREAK, RISK, COMPATIBLE, then by tier."""
    return sorted(
        zero_source_kinds(inv),
        key=lambda k: (
            _VERDICT_RANK[str(inv[k]["verdict"])],
            _TIERS.index(str(inv[k]["tier"])),
            k,
        ),
    )[:n]


def summary(inv: dict[str, dict[str, object]]) -> dict[str, object]:
    per_tier: dict[str, dict[str, int]] = {}
    for tier in _TIERS:
        members = [v for v in inv.values() if v["tier"] == tier]
        if members:
            per_tier[tier] = {
                "total": len(members),
                "zero_source": sum(1 for v in members if v["source_count"] == 0),
            }
    return {
        "total_kinds": len(inv),
        "with_real_source": sum(1 for v in inv.values() if v["source_count"]),
        "by_source": {
            s: sum(1 for v in inv.values() if v["sources"][s]) for s in SOURCES
        },  # type: ignore[index]
        "per_tier": per_tier,
        "top_gaps": most_important_gaps(inv),
    }


def render_markdown(inv: dict[str, dict[str, object]]) -> str:
    s = summary(inv)
    lines = [
        "---",
        "doc_type: contributor",
        "audience:",
        "  - maintainer",
        "level: advanced",
        "lifecycle: active",
        "generated: true",
        "---",
        "",
        GENERATED_BANNER,
        "",
        "# ChangeKind real-extraction coverage",
        "",
        "Which `ChangeKind`s are named by at least one *real end-to-end* evidence source "
        "(a compiled catalog case, a field-shape fixture, or an `integration`-marked test that "
        "asserts the kind), as opposed to unit tests on hand-built snapshots only. A kind with "
        "zero sources may have a detector the real extractors never feed. The zero-source set "
        "is a shrink-only baseline (`scripts/changekind_real_coverage_baseline.json`, gated by "
        "`tests/test_changekind_real_coverage.py`). The integration column is a lexical AST "
        "scan; its limits are in the script's `scan_integration_tests` docstring.",
        "",
        "## Headline",
        "",
        f"- Total kinds: **{s['total_kinds']}**",
        f"- Kinds with at least one real source: **{s['with_real_source']}**",
        "- Kinds per source: "
        + ", ".join(f"{k} {v}" for k, v in s["by_source"].items()),  # type: ignore[attr-defined]
        "",
        "| Tier | Kinds | Zero-source |",
        "|---|---:|---:|",
    ]
    for tier, row in s["per_tier"].items():  # type: ignore[attr-defined]
        lines.append(f"| {tier} | {row['total']} | {row['zero_source']} |")
    lines += ["", f"## Most important zero-source kinds (top {TOP_N})", ""]
    lines += ["| Kind | Verdict | Tier |", "|---|---|---|"]
    for k in s["top_gaps"]:  # type: ignore[attr-defined]
        lines.append(f"| `{k}` | {inv[k]['verdict']} | {inv[k]['tier']} |")
    for tier in _TIERS:
        rows = sorted(k for k, v in inv.items() if v["tier"] == tier)
        if not rows:
            continue
        lines += [
            "",
            f"## Tier {tier}",
            "",
            "| Kind | Verdict | Catalog | Field shapes | Integration |",
            "|---|---|---:|---:|---:|",
        ]
        for k in rows:
            src = inv[k]["sources"]
            lines.append(
                f"| `{k}` | {inv[k]['verdict']} | "
                + " | ".join(str(len(src[x])) for x in SOURCES)  # type: ignore[index]
                + " |"
            )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--check", action="store_true", help="fail if the generated doc is stale"
    )
    ap.add_argument("--json", type=Path, help="also write the full inventory as JSON")
    ap.add_argument(
        "--write-baseline", action="store_true", help="rewrite the zero-source baseline"
    )
    args = ap.parse_args(argv)
    inv = build_inventory()
    if args.json:
        args.json.write_text(
            json.dumps({"summary": summary(inv), "kinds": inv}, indent=2) + "\n",
            encoding="utf-8",
        )
    if args.write_baseline:
        BASELINE_PATH.write_text(
            json.dumps({"zero_source_kinds": zero_source_kinds(inv)}, indent=2) + "\n",
            encoding="utf-8",
        )
    text = render_markdown(inv)
    if args.check:
        if not DOC_PATH.is_file() or DOC_PATH.read_text(encoding="utf-8") != text:
            print(
                f"{DOC_PATH.relative_to(ROOT)} is stale; run `python scripts/changekind_real_coverage.py`",
                file=sys.stderr,
            )
            return 1
        return 0
    DOC_PATH.write_text(text, encoding="utf-8")
    print(json.dumps(summary(inv), indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
