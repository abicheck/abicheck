@dataclass
class RuleFamily:
    slug: str
    canonical: Case | None
    duplicates: list[Case]
    variants: list[Case]  # (case, axis) pairs kept as Case; axis on case.relation_axis
    scenarios: list[Case]
    # Multi-library bundle scenarios (ADR-023) that compose this rule too --
    # kept separate from `scenarios` because bundle cases use a different
    # ground-truth shape (no single `expected` verdict) and never get a
    # generated case page of their own (`_load_cases()` excludes them), so
    # there's no `../<name>.md` to link to. (name, short_title) pairs, not
    # `Case` objects -- a Codex review found the original cut left these
    # relationships (e.g. case90/92/93 -> exported-function-removed) visible
    # in ground_truth.json and the coverage report but silently absent here.
    bundle_scenarios: list[tuple[str, str]]


def _bundle_scenario_related_rules() -> dict[str, list[tuple[str, str]]]:
    """rule_slug -> [(bundle_case_name, short_title), ...] for every
    multi-library bundle case's own `related_rules` -- read directly from
    the taxonomy block, since `_load_cases()` deliberately excludes bundle
    cases (see its own docstring) before any Case-based grouping runs."""
    data = json.loads(GROUND_TRUTH.read_text(encoding="utf-8"))
    verdicts: dict[str, dict] = data["verdicts"]
    taxonomy: dict[str, dict] = data.get("taxonomy") or {}
    out: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for name, meta in verdicts.items():
        if not (meta.get("category") == "bundle" or meta.get("bundle") is True):
            continue
        entry = taxonomy.get(name) or {}
        for slug in entry.get("related_rules") or []:
            out[slug].append((name, _case_title(name)))
    return out


def _build_rule_families(cases: list[Case]) -> dict[str, RuleFamily]:
    families: dict[str, RuleFamily] = {}

    def _get(slug: str) -> RuleFamily:
        return families.setdefault(slug, RuleFamily(slug, None, [], [], [], []))

    for c in cases:
        if c.entity != "rule" or not c.rule_slug:
            continue
        fam = _get(c.rule_slug)
        if c.relation_type is None:
            fam.canonical = c
        elif c.relation_type == "duplicate":
            fam.duplicates.append(c)
        elif c.relation_type == "variant":
            fam.variants.append(c)
    for c in cases:
        if c.entity != "scenario":
            continue
        for slug in c.related_rules:
            _get(slug).scenarios.append(c)
    for slug, bundles in _bundle_scenario_related_rules().items():
        _get(slug).bundle_scenarios.extend(bundles)
    return families


def _render_rule_family_page(fam: RuleFamily) -> str:
    lines = [
        WARNING,
        f"# Rule: {_slug_title(fam.slug)}\n\n",
        f"_Canonical rule slug:_ `{fam.slug}`. [← back to all rules](index.md)\n\n",
    ]
    if fam.canonical is not None:
        c = fam.canonical
        vinfo = VERDICT_META[c.verdict]
        lines.append("## Canonical demonstration\n\n")
        lines.append(
            f"- [{c.name}](../{c.name}.md) — {_short_title(c.title)} "
            f"({vinfo['icon']} {vinfo['label']})\n\n"
        )
    else:
        lines.append(
            "## Canonical demonstration\n\n"
            "_No single-library case demonstrates this rule alone yet — "
            "referenced only by the scenario(s) below._\n\n"
        )
    if fam.duplicates:
        lines.append(
            "## Duplicate fixtures\n\n"
            "_Same demonstration restated with no distinguishing condition — "
            "not additional robustness coverage._\n\n"
        )
        for c in sorted(fam.duplicates, key=lambda c: _case_sort_key(c.name)):
            lines.append(f"- [{c.name}](../{c.name}.md) — {_short_title(c.title)}\n")
        lines.append("\n")
    if fam.variants:
        lines.append(
            "## Variants\n\n"
            "_The same rule demonstrated under a different condition._\n\n"
        )
        for c in sorted(fam.variants, key=lambda c: _case_sort_key(c.name)):
            axis = f" ({c.relation_axis})" if c.relation_axis else ""
            lines.append(
                f"- [{c.name}](../{c.name}.md) — {_short_title(c.title)}{axis}\n"
            )
        lines.append("\n")
    if fam.scenarios:
        lines.append("## Used by scenarios\n\n")
        for c in sorted(fam.scenarios, key=lambda c: _case_sort_key(c.name)):
            lines.append(f"- [{c.name}](../{c.name}.md) — {_short_title(c.title)}\n")
        lines.append("\n")
    if fam.bundle_scenarios:
        lines.append(
            "## Used by multi-library bundle scenarios\n\n"
            "_ADR-023 bundle cases aren't part of this single-library "
            "catalog (see `examples/README.md`), so these aren't linked "
            "pages here — see the case's own README under `examples/`._\n\n"
        )
        for name, title in sorted(fam.bundle_scenarios):
            lines.append(f"- `{name}` — {title}\n")
        lines.append("\n")
    return "".join(lines)


def _render_by_rule_index(families: dict[str, RuleFamily]) -> str:
    lines = [
        WARNING,
        "# Rule families\n\n",
        "Every atomic, ecosystem-neutral compatibility rule the catalog "
        "demonstrates or references, deduplicated across duplicate/variant "
        "restatements and composed scenarios. See "
        "[Rule coverage](../../../contribute/catalog-coverage.md) for the "
        "aggregate counts this table is drawn from. "
        "[← back to all examples](../index.md)\n\n",
        "| Rule | Canonical case | Duplicate(s) | Variant(s) | Scenario(s) | Bundle scenario(s) |\n",
        "|---|---|---|---|---|---|\n",
    ]
    for slug in sorted(families):
        fam = families[slug]
        canonical_cell = (
            f"[{fam.canonical.name}](../{fam.canonical.name}.md)"
            if fam.canonical
            else "—"
        )
        dup_cell = (
            ", ".join(f"[{c.name}](../{c.name}.md)" for c in fam.duplicates) or "—"
        )
        var_cell = ", ".join(f"[{c.name}](../{c.name}.md)" for c in fam.variants) or "—"
        scenario_cell = (
            ", ".join(f"[{c.name}](../{c.name}.md)" for c in fam.scenarios) or "—"
        )
        bundle_cell = (
            ", ".join(f"`{name}`" for name, _title in sorted(fam.bundle_scenarios))
            or "—"
        )
        lines.append(
            f"| [`{slug}`]({slug}.md) | {canonical_cell} | {dup_cell} | "
            f"{var_cell} | {scenario_cell} | {bundle_cell} |\n"
        )
    return "".join(lines)


# ---------------------------------------------------------------------------
# examples/README.md catalog (the GitHub-facing index, not the docs site).
#
# Three regions are generated between sentinel comments so the headline count,
# verdict distribution, and 126-row case index can't drift from ground_truth.
# Bundle cases (skipped by the docs-site generator) ARE included here, since the
# README indexes the whole catalog.
# ---------------------------------------------------------------------------


@dataclass
class ReadmeEntry:
    num: str  # case number as it appears in the dir name, e.g. "01", "26b", "110"
    name: str
    title: str
    category: str
    verdict: str  # ground_truth "expected", or "BUNDLE" for multi-library cases
    bad_practice: bool


def _case_title(name: str) -> str:
    """Short H1 title of a per-case README (caseNN prefix stripped)."""
    text = (example_catalog.case_dir(name) / "README.md").read_text(encoding="utf-8")
    m = re.match(r"\s*#\s+(.+?)\n", text)
    if not m:
        raise ValueError(f"examples/{name}/README.md: first line must be an H1")
    return _short_title(m.group(1).strip())


def _load_readme_entries() -> list[ReadmeEntry]:
    data = json.loads(GROUND_TRUTH.read_text(encoding="utf-8"))
    entries: list[ReadmeEntry] = []
    for name, meta in data["verdicts"].items():
        m = re.match(r"case(\d+[a-z]?)", name)
        if not m:
            raise ValueError(f"unexpected case name {name!r}")
        category = meta.get("category")
        verdict = "BUNDLE" if category == "bundle" else meta["expected"]
        entries.append(
            ReadmeEntry(
                num=m.group(1),
                name=name,
                title=_case_title(name),
                category=category,
                verdict=verdict,
                bad_practice=bool(meta.get("bad_practice", False)),
            )
        )
    entries.sort(key=lambda e: (int(re.match(r"(\d+)", e.num).group(1)), e.name))
    return entries


def _render_readme_headline(entries: list[ReadmeEntry]) -> str:
    n_total = len(entries)
    n_bundle = sum(1 for e in entries if e.category == "bundle")
    n_single = n_total - n_bundle
    return (
        f"This directory contains **{n_total} cases** "
        f"({n_single} single-library + {n_bundle} multi-library bundle cases, "
        "the latter tracked under "
        "[ADR-023](../docs/contribute/adr/023-bundle-aware-multi-binary-analysis.md)) "
        "demonstrating real-world ABI/API break scenarios. Most cases are a "
        "minimal, compilable C/C++ example with:"
    )


def _render_readme_distribution(entries: list[ReadmeEntry]) -> str:
    single = [e for e in entries if e.category != "bundle"]
    n_bundle = len(entries) - len(single)
    by_verdict = Counter(e.verdict for e in single)
    by_category = Counter(e.category for e in single)
    rows = [
        ("BREAKING", by_verdict.get("BREAKING", 0), "`BREAKING_KINDS`", "🔴"),
        ("API_BREAK", by_verdict.get("API_BREAK", 0), "`API_BREAK_KINDS`", "🟠"),
        (
            "COMPATIBLE_WITH_RISK",
            by_verdict.get("COMPATIBLE_WITH_RISK", 0),
            "`RISK_KINDS`",
            "🟡",
        ),
        (
            "COMPATIBLE (addition)",
            by_category.get("addition", 0),
            "`ADDITION_KINDS`",
            "🟢",
        ),
        (
            "COMPATIBLE (quality)",
            by_category.get("quality", 0),
            "`QUALITY_KINDS`",
            "🟡",
        ),
        ("NO_CHANGE", by_verdict.get("NO_CHANGE", 0), "—", "✅"),
        (
            "Bundle (multi-binary)",
            n_bundle,
            "see [ADR-023](../docs/contribute/adr/023-bundle-aware-multi-binary-analysis.md)",
            "🔵",
        ),
    ]
    lines = [
        "| Verdict | Count | `checker_policy.py` set | Icon |",
        "|---------|-------|-------------------------|------|",
    ]
    lines += [
        f"| {label} | {count} | {kset} | {icon} |" for label, count, kset, icon in rows
    ]
    return "\n".join(lines)


def _render_readme_index(entries: list[ReadmeEntry]) -> str:
    lines = [
        "| # | Case | Category | abicheck verdict |",
        "|---|------|----------|-----------------|",
    ]
    for e in entries:
        icon = VERDICT_META[e.verdict]["icon"] if e.verdict in VERDICT_META else "🔵"
        cell = f"{icon} {e.verdict}"
        if e.bad_practice:
            cell += " (bad practice)"
        lines.append(
            f"| [{e.num}]({e.name}/README.md) | {e.title} "
            f"| {README_CATEGORY_LABEL[e.category]} | {cell} |"
        )
    return "\n".join(lines)


def _splice_generated(text: str, marker: str, inner: str) -> str:
    """Replace the text between BEGIN/END GENERATED sentinels for ``marker``."""
    begin = re.search(rf"<!-- BEGIN GENERATED: {re.escape(marker)}[^\n]*-->\n", text)
    end = re.search(rf"\n<!-- END GENERATED: {re.escape(marker)} -->", text)
    if not begin or not end or begin.end() > end.start():
        raise ValueError(
            f"examples/README.md: missing/!ordered sentinels for {marker!r}"
        )
    return text[: begin.end()] + inner + text[end.start() :]


def _render_examples_readme(text: str, entries: list[ReadmeEntry]) -> str:
    text = _splice_generated(text, "catalog-headline", _render_readme_headline(entries))
    text = _splice_generated(
        text, "verdict-distribution", _render_readme_distribution(entries)
    )
    text = _splice_generated(text, "case-index", _render_readme_index(entries))
    return text


def _load_cases() -> list[Case]:
    data = json.loads(GROUND_TRUTH.read_text(encoding="utf-8"))
    taxonomy_block: dict[str, dict] = data.get("taxonomy") or {}
    cases = []
    for name, meta in data["verdicts"].items():
        # Bundle cases (ADR-023) are multi-library and use a different
        # ground-truth shape (expected=null, per-library verdicts under
        # library_assertions, bundle-level verdict under
        # canonical aggregate expected verdict). They have their own README files
        # but don't map onto the per-case verdict-page generator; skip
        # them here. The bundle index belongs in a follow-up doc page.
        if meta.get("category") == "bundle" or meta.get("bundle") is True:
            continue
        if meta["expected"] not in VERDICT_META:
            raise ValueError(f"{name}: unknown verdict {meta['expected']!r}")
        if meta["category"] not in CATEGORY_META:
            raise ValueError(f"{name}: unknown category {meta['category']!r}")
        cases.append(_read_case(name, meta, taxonomy_block.get(name, {})))
    return cases


def _write(path: Path, content: str) -> None:
    # Write in binary with LF newlines so the on-disk tree is byte-stable across
    # platforms — required for the --check drift gate to work on Windows.
    path.write_bytes(content.encode("utf-8"))


def _normalize(data: bytes) -> bytes:
    # Strip BOM and normalize CRLF/CR → LF so the comparator survives a Windows
    # checkout where core.autocrlf might have rewritten committed files.
    if data.startswith(b"\xef\xbb\xbf"):
        data = data[3:]
    return data.replace(b"\r\n", b"\n").replace(b"\r", b"\n")


def _files_match(a: Path, b: Path) -> bool:
    return _normalize(a.read_bytes()) == _normalize(b.read_bytes())


def _write_tree(out_dir: Path, cases: list[Case]) -> None:
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)
    (out_dir / "by-verdict").mkdir()
    (out_dir / "by-category").mkdir()
    (out_dir / "by-rule").mkdir()
    (out_dir / "by-ecosystem").mkdir()

    _write(out_dir / "index.md", _render_index(cases))

    by_verdict: dict[str, list[Case]] = defaultdict(list)
    by_category: dict[str, list[Case]] = defaultdict(list)
    by_ecosystem: dict[str, list[Case]] = defaultdict(list)
    for c in cases:
        by_verdict[c.verdict].append(c)
        by_category[c.category].append(c)
        by_ecosystem[c.ecosystem].append(c)

    for v in VERDICT_ORDER:
        info = VERDICT_META[v]
        _write(
            out_dir / "by-verdict" / f"{info['slug']}.md",
            _render_group_index(
                title=f"{info['icon']} {info['label']} cases",
                blurb=info["blurb"],
                cases=by_verdict.get(v, []),
            ),
        )

    for cat in CATEGORY_ORDER:
        info = CATEGORY_META[cat]
        _write(
            out_dir / "by-category" / f"{cat}.md",
            _render_group_index(
                title=f"{info['label']} cases",
                blurb=info["blurb"],
                cases=by_category.get(cat, []),
            ),
        )

    for eco in ECOSYSTEM_ORDER:
        info_label = ECOSYSTEM_LABEL[eco]
        _write(
            out_dir / "by-ecosystem" / f"{eco}.md",
            _render_group_index(
                title=f"{info_label} cases",
                blurb=f"Cases modeling the {info_label} ecosystem.",
                cases=by_ecosystem.get(eco, []),
            ),
        )

    rule_families = _build_rule_families(cases)
    _write(out_dir / "by-rule" / "index.md", _render_by_rule_index(rule_families))
    for slug, fam in rule_families.items():
        _write(out_dir / "by-rule" / f"{slug}.md", _render_rule_family_page(fam))

    for c in cases:
        _write(out_dir / f"{c.name}.md", _render_case_page(c))


def _trees_match(a: Path, b: Path) -> bool:
    cmp = filecmp.dircmp(a, b)
    if cmp.left_only or cmp.right_only or cmp.funny_files:
        return False
    for f in cmp.common_files:
        if not _files_match(a / f, b / f):
            return False
    for sub in cmp.common_dirs:
        if not _trees_match(a / sub, b / sub):
            return False
    return True


def _print_diff(expected: Path, actual: Path) -> None:
    cmp = filecmp.dircmp(expected, actual)
    if cmp.left_only:
        print(f"  missing in {actual}: {cmp.left_only}", file=sys.stderr)
    if cmp.right_only:
        print(f"  stale in {actual}: {cmp.right_only}", file=sys.stderr)
    diffs = [f for f in cmp.common_files if not _files_match(expected / f, actual / f)]
    if diffs:
        print(f"  changed: {diffs}", file=sys.stderr)
    for sub in cmp.common_dirs:
        _print_diff(expected / sub, actual / sub)


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail (exit 1) if the on-disk tree differs from what would be generated.",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)

    cases = _load_cases()
    readme_entries = _load_readme_entries()
    readme_current = EXAMPLES_README.read_text(encoding="utf-8")
    readme_rendered = _render_examples_readme(readme_current, readme_entries)

    if args.check:
        ok = True
        with tempfile.TemporaryDirectory() as tmp:
            tmp_out = Path(tmp) / "examples"
            _write_tree(tmp_out, cases)
            if not DOCS_EXAMPLES_DIR.exists() or not _trees_match(
                tmp_out, DOCS_EXAMPLES_DIR
            ):
                print(
                    "docs/reference/examples/ is out of date. Run: python scripts/gen_examples_docs.py",
                    file=sys.stderr,
                )
                if DOCS_EXAMPLES_DIR.exists():
                    _print_diff(tmp_out, DOCS_EXAMPLES_DIR)
                ok = False
        if _normalize(readme_rendered.encode("utf-8")) != _normalize(
            readme_current.encode("utf-8")
        ):
            print(
                "examples/README.md generated regions are out of date. "
                "Run: python scripts/gen_examples_docs.py",
                file=sys.stderr,
            )
            ok = False
        if not ok:
            return 1
        print(
            f"docs/reference/examples/ and examples/README.md are up to date ({len(cases)} cases)."
        )
        return 0

    _write_tree(DOCS_EXAMPLES_DIR, cases)
    _write(EXAMPLES_README, readme_rendered)
    print(
        f"Generated {len(cases)} case pages in {DOCS_EXAMPLES_DIR.relative_to(ROOT)}/ "
        f"and refreshed examples/README.md ({len(readme_entries)} catalog rows)."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
