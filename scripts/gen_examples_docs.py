def _read_case(name: str, meta: dict, taxonomy: dict) -> Case:
    readme = example_catalog.case_dir(name) / "README.md"
    if not readme.exists():
        raise FileNotFoundError(f"missing per-case README: {readme}")
    text = readme.read_text(encoding="utf-8")
    m = re.match(r"\s*#\s+(.+?)\n", text)
    if not m:
        raise ValueError(f"{readme}: first line must be H1 (# Title)")
    title = m.group(1).strip()
    body = text[m.end() :].lstrip("\n")
    body = _rewrite_links(body)
    return Case(
        name=name,
        title=title,
        verdict=meta["expected"],
        category=meta["category"],
        platforms=list(meta.get("platforms", [])),
        abi_break=bool(meta.get("abi_break", False)),
        api_break=bool(meta.get("api_break", False)),
        bad_practice=bool(meta.get("bad_practice", False)),
        expected_kinds=list(meta.get("expected_kinds", [])),
        body=body,
        underlying_fact=meta.get("underlying_fact"),
        policy_note=meta.get("policy_note"),
        detectability=meta.get("detectability"),
        known_detector_gap=meta.get("known_detector_gap"),
        known_kind_gap=meta.get("known_kind_gap"),
        known_kind_gap_note=meta.get("known_kind_gap_note"),
        entity=taxonomy.get("entity", "rule"),
        scenario_kind=taxonomy.get("scenario_kind"),
        operation=taxonomy.get("operation", "compare"),
        ecosystem=taxonomy.get("ecosystem", "generic"),
        rule_slug=taxonomy.get("rule_slug"),
        variant_of=taxonomy.get("variant_of"),
        relation_type=taxonomy.get("relation_type"),
        relation_axis=taxonomy.get("relation_axis"),
        related_rules=list(taxonomy.get("related_rules") or []),
    )


def _rewrite_links(body: str) -> str:
    # Rewrite links from examples/<case>/README.md for generated docs. MkDocs
    # strict mode validates Markdown links against files under docs/, so source
    # files outside docs/ are rendered as code literals instead of links.
    def repl(m: re.Match) -> str:
        text, target = m.group(1), m.group(2)
        if target.startswith(("http://", "https://", "#", "mailto:")):
            return m.group(0)
        # A case README lives two levels below the repo root
        # (examples/<case>/README.md), so a link into docs/ from there is
        # "../../docs/..." — but a source file one level up (e.g. from
        # examples/README.md itself) could write "../docs/...". Match either
        # depth of leading "../" before "docs/".
        docs_target = re.match(r"^(?:\.\./)+docs/(.*)$", target)
        if docs_target:
            # docs_target.group(1) is docs/-relative (e.g. "reference/change-
            # kinds.md"), independent of where this generated page itself
            # lives. Compute the link relative to the *generated* page's
            # actual location (docs/reference/examples/), not a hard-coded
            # single "../" -- that assumption broke when examples/ moved one
            # level deeper, under reference/.
            url = posixpath.relpath(
                docs_target.group(1), start=DOCS_EXAMPLES_DIR_FROM_DOCS_ROOT
            )
            return f"[{text}]({url})"
        # Bare filenames like v1.c, app.cpp and ../ source-tree paths live
        # outside docs/; keep the reference visible without creating a checked
        # MkDocs link.
        if target.startswith("../") or ("/" not in target and "." in target):
            return f"`{text.strip('`')}`"
        return f"[{text}]({target})"

    return re.sub(r"\[([^\]]+)\]\(([^)]+)\)", repl, body)


def _classification_label(case: Case) -> str:
    if case.entity == "scenario":
        skind = SCENARIO_KIND_LABEL.get(case.scenario_kind, case.scenario_kind or "—")
        label = f"Scenario — {skind}"
    else:
        label = "Rule"
    if case.operation == "audit":
        label += " · audit"
    return label


def _rule_family_row(case: Case) -> str:
    """A rule-entity case's rule_slug, plus its duplicate/variant relation to
    a canonical case when it has one — the taxonomy this PR's own review
    finding asked for: "internally the repository understands the cases
    are different... externally users still see a flat catalog"."""
    if not case.rule_slug:
        return ""
    slug_link = f"[`{case.rule_slug}`](by-rule/{case.rule_slug}.md)"
    if not case.relation_type:
        return f"| **Rule family** | {slug_link} |\n"
    rel = RELATION_TYPE_LABEL.get(case.relation_type, case.relation_type)
    axis = f" ({case.relation_axis})" if case.relation_axis else ""
    canonical_link = (
        f"[{case.variant_of}]({case.variant_of}.md)" if case.variant_of else "—"
    )
    return f"| **Rule family** | {slug_link} — {rel}{axis} of {canonical_link} |\n"


def _related_rules_row(case: Case) -> str:
    if not case.related_rules:
        return ""
    links = ", ".join(f"[`{s}`](by-rule/{s}.md)" for s in case.related_rules)
    return f"| **Related rules** | {links} |\n"


def _meta_table(case: Case) -> str:
    vinfo = VERDICT_META[case.verdict]
    cinfo = CATEGORY_META[case.category]
    flags = []
    if case.abi_break:
        flags.append("ABI break")
    if case.api_break:
        flags.append("API break")
    if case.bad_practice:
        flags.append("Bad practice")
    flag_str = ", ".join(flags) if flags else "—"
    platforms = (
        ", ".join(PLATFORM_DISPLAY.get(p, p) for p in case.platforms)
        if case.platforms
        else "—"
    )
    kinds = (
        ", ".join(f"`{k}`" for k in case.expected_kinds) if case.expected_kinds else "—"
    )
    rows = (
        "| Field | Value |\n"
        "|-------|-------|\n"
        f"| **Verdict** | {vinfo['icon']} **{vinfo['label']}** |\n"
        f"| **Category** | {cinfo['label']} |\n"
        f"| **Classification** | {_classification_label(case)} |\n"
        f"| **Platforms** | {platforms} |\n"
        f"| **Flags** | {flag_str} |\n"
        f"| **Detected `ChangeKind`s** | {kinds} |\n"
        f"| **Source files** | `examples/{case.name}/` |\n"
    )
    if case.ecosystem != "generic":
        eco_link = f"[{ECOSYSTEM_LABEL.get(case.ecosystem, case.ecosystem)}](by-ecosystem/{case.ecosystem}.md)"
        rows += f"| **Ecosystem** | {eco_link} |\n"
    rows += _rule_family_row(case)
    rows += _related_rules_row(case)
    # Fact vs. policy: only present when ground_truth.json's `expected` is a
    # policy escalation of a weaker underlying compatibility fact (case30,
    # case95, case109-style) — see policy_note in ground_truth.json.
    if case.underlying_fact and case.underlying_fact != case.verdict:
        rows += f"| **Underlying fact** | {case.underlying_fact} (policy-escalated to {case.verdict}) |\n"
    # Detectability: only present for a case where no L0-L5 evidence tier
    # currently reaches the canonical verdict (case111-style known gap).
    if case.detectability == "none":
        rows += "| **Detectability** | None — no evidence tier currently proves this verdict (known detector gap) |\n"
    if case.known_detector_gap:
        rows += f"| **Known detector gap** | `{case.known_detector_gap}` |\n"
    # Kind gap: the verdict/severity is correct, but the specific calibrated
    # ChangeKind above is not what the tool currently emits (case06-style).
    if case.known_kind_gap:
        rows += f"| **Known kind gap** | `{case.known_kind_gap}` — verdict is correct; see note below |\n"
    return rows


def _source_links(case: Case) -> str:
    case_dir = example_catalog.case_dir(case.name)
    files = sorted(
        p.name for p in case_dir.iterdir() if p.is_file() and p.name != "README.md"
    )
    if not files:
        return ""
    lines = [f"- `{f}`" for f in files]
    return "## Source files\n\n" + "\n".join(lines) + "\n"


def _provenance_notes(case: Case) -> str:
    """Render policy_note/known_kind_gap_note prose when ground_truth.json sets
    them, so the fact-vs-policy or kind-gap distinction is visible in the
    generated docs rather than only in the raw JSON."""
    parts = []
    if case.policy_note:
        parts.append(f"**Policy note:** {case.policy_note}\n")
    if case.known_kind_gap_note:
        parts.append(f"**Known kind gap:** {case.known_kind_gap_note}\n")
    if not parts:
        return ""
    return "## Ground-truth provenance\n\n" + "\n".join(parts) + "\n"


def _render_case_page(case: Case) -> str:
    body = case.body.replace("__CASE__", case.name)
    see_also = [
        "[Examples overview](index.md)",
        f"[All {VERDICT_META[case.verdict]['label']} cases]"
        f"(by-verdict/{VERDICT_META[case.verdict]['slug']}.md)",
        f"[Category: {CATEGORY_META[case.category]['label']}](by-category/{case.category}.md)",
    ]
    if case.rule_slug:
        see_also.append(
            f"[Rule: {_slug_title(case.rule_slug)}](by-rule/{case.rule_slug}.md)"
        )
    if case.ecosystem != "generic":
        see_also.append(
            f"[Ecosystem: {ECOSYSTEM_LABEL.get(case.ecosystem, case.ecosystem)}]"
            f"(by-ecosystem/{case.ecosystem}.md)"
        )
    parts = [
        WARNING,
        f"# {case.title}\n\n",
        _meta_table(case),
        "\n",
        body.rstrip() + "\n\n",
        "---\n\n",
        _provenance_notes(case),
        _source_links(case),
        "\n",
        f"_See also: {' · '.join(see_also)}._\n",
    ]
    return "".join(parts)


def _verdict_counts(cases: list[Case]) -> dict[str, int]:
    out: dict[str, int] = defaultdict(int)
    for c in cases:
        out[c.verdict] += 1
    return out


def _case_sort_key(name: str) -> tuple[int, str]:
    """Order cases by their numeric index (case2 < case10 < case109), with the
    optional letter suffix (case26 < case26b) as the tiebreak. Lexical sorting
    would otherwise interleave case10 between case1 and case2."""
    m = re.match(r"case(\d+)([a-z]*)", name)
    if not m:
        return (10**9, name)
    return (int(m.group(1)), m.group(2))


def _case_row(case: Case) -> str:
    vinfo = VERDICT_META[case.verdict]
    return (
        f"| [{case.name}]({case.name}.md) "
        f"| {_short_title(case.title)} "
        f"| {vinfo['icon']} {vinfo['label']} "
        f"| {CATEGORY_META[case.category]['label']} |"
    )


