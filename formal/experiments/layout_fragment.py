#!/usr/bin/env python3
"""The closed layout fragment: generator, compiler check and abicheck run.

Fragment (formal/FRAGMENT.md): insert one scalar field (size = alignment in
{1, 2, 4, 8}) at any position into a C struct of 1..4 such fields, LP64 SysV.
The case space, the oracle and the class key come from Lean
(``formal/lean/AbiLean/Fragment.lean``, exported to
``formal/lean/fragment_cases.json``). This module holds:

* ``generate()`` -- the C generator. It enumerates program pairs with its own
  loops (a different order from Lean's ``space``) and never reads the Lean
  export; ``decode()`` parses a generated pair back to a case. The bijection
  between the two is checked by ``tests/test_formal_layout_fragment.py``.
* ``run()`` -- builds every selected case with gcc and clang, compares the
  compilers' sizeof/_Alignof/offsetof with the Lean oracle, and runs
  ``abicheck compare`` on each compiler's build, comparing findings and
  verdict per case with the oracle.

Usage::

    layout_fragment.py OUT_DIR [--reduced] [--per-case] [--compilers gcc,clang]

writes OUT_DIR/summary.json. Needs gcc/clang, castxml and abicheck on PATH.
"""

from __future__ import annotations

import argparse
import itertools
import json
import re
import shutil
import subprocess
import sys
import time
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXPORT = HERE.parent / "lean" / "fragment_cases.json"

#: The generator's C spelling of each size class (bytes = size = alignment on
#: LP64 SysV). The compile step asserts the premise with _Static_assert.
CTYPE = {1: "char", 2: "short", 4: "int", 8: "long"}
SIZES = (1, 2, 4, 8)
MAX_FIELDS = 4
PREMISE = "\n".join(
    f"_Static_assert(sizeof({t}) == {n} && _Alignof({t}) == {n}, "
    f'"LP64 SysV premise: {t} is {n} bytes, {n}-aligned");'
    for n, t in CTYPE.items()
)


@dataclass(frozen=True)
class Program:
    """A generated program pair: the old and new struct bodies."""

    old_body: str
    new_body: str


def _body(decls: list[tuple[str, str]]) -> str:
    return " ".join(f"{t} {n};" for t, n in decls)


def generate() -> list[Program]:
    """Every program pair of the fragment, enumerated by the generator itself.

    Order: inserted size (descending), struct length (descending), position
    (descending), then the old field types -- deliberately not Lean's order,
    so agreement is a check rather than a copy.
    """
    out = []
    for ins in reversed(SIZES):
        for n in range(MAX_FIELDS, 0, -1):
            for pos in range(n, -1, -1):
                for base in itertools.product(SIZES, repeat=n):
                    old = [(CTYPE[b], f"f{j}") for j, b in enumerate(base)]
                    new = old[:pos] + [(CTYPE[ins], "ins")] + old[pos:]
                    out.append(Program(_body(old), _body(new)))
    return out


_DECL = re.compile(r"(\w+) (\w+);")
_SIZE_OF = {t: n for n, t in CTYPE.items()}


def decode(p: Program) -> tuple[tuple[int, ...], int, int] | None:
    """Parse a program pair back to ``(base sizes, pos, inserted size)``.

    Returns None unless the pair is exactly what the generator emits for some
    case of the space: old fields named f0..f(n-1) in order with a known
    scalar type, 1 <= n <= 4, and the new body the old one with a single
    ``ins`` field inserted.
    """
    old = _DECL.findall(p.old_body)
    new = _DECL.findall(p.new_body)
    if _body(old) != p.old_body or _body(new) != p.new_body:
        return None
    if not 1 <= len(old) <= MAX_FIELDS:
        return None
    if [n for _, n in old] != [f"f{j}" for j in range(len(old))]:
        return None
    if any(t not in _SIZE_OF for t, _ in old + new):
        return None
    ins_at = [i for i, (_, n) in enumerate(new) if n == "ins"]
    if len(ins_at) != 1:
        return None
    pos = ins_at[0]
    if new[:pos] + new[pos + 1 :] != old:
        return None
    return tuple(_SIZE_OF[t] for t, _ in old), pos, _SIZE_OF[new[pos][0]]


def load_export() -> dict:
    return json.loads(EXPORT.read_text(encoding="utf-8"))


# --------------------------------------------------------------------- build


def _run(cmd: list[str], **kw) -> subprocess.CompletedProcess[str]:
    return subprocess.run(cmd, capture_output=True, text=True, **kw)  # noqa: S603


def _write_sources(out: Path, rows: list[dict]) -> None:
    for side in ("old", "new"):
        h = ["/* generated by formal/experiments/layout_fragment.py */", PREMISE]
        c = [f'#include "{side}.h"']
        probe = [
            "#include <stdio.h>",
            "#include <stddef.h>",
            f'#include "{side}.h"',
            "int main(void){",
        ]
        for r in rows:
            i, body = r["id"], r[f"{side}_body"]
            h.append(f"struct s{i} {{ {body} }};")
            h.append(f"int use_s{i}(struct s{i} *p);")
            c.append(f"int use_s{i}(struct s{i} *p) {{ return (int)p->f0; }}")
            names = [n for _, n in _DECL.findall(body)]
            offs = ",".join(f"(int)offsetof(struct s{i},{n})" for n in names)
            fmt = " ".join("%d" for _ in names)
            probe.append(
                f'printf("{i} %d %d {fmt}\\n",(int)sizeof(struct s{i}),'
                f"(int)_Alignof(struct s{i}),{offs});"
            )
        probe.append("return 0;}")
        (out / f"{side}.h").write_text("\n".join(h) + "\n")
        (out / f"{side}.c").write_text("\n".join(c) + "\n")
        (out / f"probe_{side}.c").write_text("\n".join(probe) + "\n")


def _build(out: Path, cc: str) -> dict[str, dict[int, tuple[list[int], int, int]]]:
    """Build both sides with ``cc``; return the compiler's layouts per side."""
    layouts = {}
    for side in ("old", "new"):
        _run(
            [
                cc,
                "-std=c11",
                "-g",
                "-O0",
                "-shared",
                "-fPIC",
                "-I",
                str(out),
                str(out / f"{side}.c"),
                "-o",
                str(out / f"lib{side}_{cc}.so"),
            ],
            check=True,
        )
        exe = out / f"probe_{side}_{cc}"
        _run(
            [
                cc,
                "-std=c11",
                "-I",
                str(out),
                str(out / f"probe_{side}.c"),
                "-o",
                str(exe),
            ],
            check=True,
        )
        res = {}
        for line in _run([str(exe)], check=True).stdout.splitlines():
            i, size, align, *offs = map(int, line.split())
            res[i] = (offs, size, align)
        layouts[side] = res
    return layouts


_MEMBER = re.compile(r": (s\d+)::(\w+) ")


def _compare(out: Path, cc: str) -> tuple[int, dict[str, list[dict]]]:
    rep = out / f"compare_{cc}.json"
    rep.unlink(missing_ok=True)
    proc = _run(
        [
            "abicheck",
            "compare",
            str(out / f"libold_{cc}.so"),
            str(out / f"libnew_{cc}.so"),
            "--header",
            f"old={out / 'old.h'}",
            "--header",
            f"new={out / 'new.h'}",
            "-o",
            f"json={rep}",
        ]
    )
    if proc.returncode not in (0, 2, 4) or not rep.exists():
        sys.stderr.write(proc.stderr)
        raise SystemExit(f"abicheck compare ({cc}) failed with exit {proc.returncode}")
    by_rec: dict[str, list[dict]] = {}
    for c in json.loads(rep.read_text(encoding="utf-8"))["changes"]:
        by_rec.setdefault(c["symbol"].split("::")[0], []).append(c)
    return proc.returncode, by_rec


def observed(changes: list[dict]) -> tuple[list[str], str]:
    """A case's findings as ``kind:member`` (record-level: ``kind:``) and verdict."""
    fs = []
    for c in changes:
        m = _MEMBER.search(c.get("description", "") + " ")
        fs.append(f"{c['kind']}:{m.group(2) if m else ''}")
    verdict = (
        "breaking"
        if any(c["severity"] == "breaking" for c in changes)
        else (
            "compatible"
            if all(c["severity"] == "compatible" for c in changes)
            else "other"
        )
    )
    return sorted(fs), verdict


def check_batch(
    out: Path, rows: list[dict], classes: list[dict], compilers: tuple[str, ...]
) -> dict:
    """All selected cases in one library pair per compiler."""
    out.mkdir(parents=True, exist_ok=True)
    _write_sources(out, rows)
    res: dict = {"cases": len(rows), "compilers": {}}
    for cc in compilers:
        t0 = time.perf_counter()
        lay = _build(out, cc)
        t1 = time.perf_counter()
        _, by_rec = _compare(out, cc)
        t2 = time.perf_counter()
        layout_bad, abi_bad = [], []
        for r in rows:
            for side in ("old", "new"):
                if lay[side][r["id"]] != tuple(r[side]):
                    layout_bad.append((r["id"], side, lay[side][r["id"]], r[side]))
            cls = classes[r["class"]]
            got = observed(by_rec.get(f"s{r['id']}", []))
            want = (sorted(cls["findings"]), cls["verdict"])
            if got != want:
                abi_bad.append((r["id"], got, want))
        res["compilers"][cc] = {
            "layout_agree": 2 * len(rows) - len(layout_bad),
            "layout_disagree": len(layout_bad),
            "abicheck_agree": len(rows) - len(abi_bad),
            "abicheck_disagree": len(abi_bad),
            "layout_examples": layout_bad[:5],
            "abicheck_examples": abi_bad[:5],
            "seconds_build_and_probe": round(t1 - t0, 2),
            "seconds_abicheck": round(t2 - t1, 2),
        }
    return res


def _one_case(out: Path, row: dict, cls: dict, compilers: tuple[str, ...]) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    _write_sources(out, [row])
    r = {"id": row["id"]}
    for cc in compilers:
        lay = _build(out, cc)
        code, by_rec = _compare(out, cc)
        got = observed(by_rec.get(f"s{row['id']}", []))
        r[cc] = {
            "layout_ok": all(
                lay[s][row["id"]] == tuple(row[s]) for s in ("old", "new")
            ),
            "abicheck_ok": got == (sorted(cls["findings"]), cls["verdict"]),
            # per-case run: the exit code is this case's own verdict
            "exit_ok": code == (4 if cls["verdict"] == "breaking" else 0),
        }
    shutil.rmtree(out)  # ~0.3 MB per case; the full per-case run would need ~2 GB
    return r


def check_per_case(
    out: Path,
    rows: list[dict],
    classes: list[dict],
    compilers: tuple[str, ...],
    jobs: int,
) -> dict:
    """Each case as its own library pair and compare run (true per-case exit code)."""
    with ThreadPoolExecutor(max_workers=jobs) as ex:
        results = list(
            ex.map(
                lambda r: _one_case(
                    out / f"c{r['id']}", r, classes[r["class"]], compilers
                ),
                rows,
            )
        )
    summary: dict = {"cases": len(rows), "compilers": {}}
    for cc in compilers:
        summary["compilers"][cc] = dict(
            Counter(
                f"layout={x[cc]['layout_ok']} abicheck={x[cc]['abicheck_ok']} exit={x[cc]['exit_ok']}"
                for x in results
            )
        )
    summary["bad"] = [
        x for x in results if not all(all(x[cc].values()) for cc in compilers)
    ][:5]
    return summary


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("out", type=Path)
    ap.add_argument("--reduced", action="store_true", help="only class representatives")
    ap.add_argument(
        "--per-case", action="store_true", help="one build+compare per case"
    )
    ap.add_argument("--compilers", default="gcc,clang")
    ap.add_argument("--jobs", type=int, default=4)
    a = ap.parse_args(argv)
    data = load_export()
    rows, classes = data["rows"], data["classes"]
    if a.reduced:
        rows = [r for r in rows if r["rep"]]
    compilers = tuple(a.compilers.split(","))
    t0 = time.perf_counter()
    if a.per_case:
        res = check_per_case(a.out, rows, classes, compilers, a.jobs)
    else:
        res = check_batch(a.out, rows, classes, compilers)
    res["mode"] = ("per-case" if a.per_case else "batch") + (
        " reduced" if a.reduced else " full"
    )
    res["wall_seconds"] = round(time.perf_counter() - t0, 2)
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "summary.json").write_text(json.dumps(res, indent=1))
    print(json.dumps(res, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
